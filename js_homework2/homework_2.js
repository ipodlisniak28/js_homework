
/* ДЗ №2: Функція pow(x, y) */

function pow(x, y) {
/* 1. Будь-яке число в степені 0 дорівнює 1 */
    if (y === 0) {
        return 1;
    }

/* 2. Зберігаємо результат. Починаємо з 1 (нейтральне число для множення) */
    let result = 1;

/* 3. Обробка від'ємних ступенів.
Якщо y < 0, ми робимо його додатним для циклу. */
    let count = y;
    if (y < 0) {
        count = -y; /* Робимо позитивним (наприклад -3 стає 3) */
    }

/* 4. Головний цикл - множимо x на себе count разів */
    for (let i = 0; i < count; i++) {
        result = result * x;
    }

/* 5. Якщо ступінь був від'ємним, ділимо 1 на результат */
    if (y < 0) {
        return 1 / result;
    }

    return result;
}

/* Перевірка (тести) */
console.log("2 в степені 3:", pow(2, 3));   /* 8 */
console.log("5 в степені 2:", pow(5, 2));   /* 25 */
console.log("10 в степені 0:", pow(10, 0)); /* 1 */
console.log("2 в степені -3:", pow(2, -3)); /* 0.125 */